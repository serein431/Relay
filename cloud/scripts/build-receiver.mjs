import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const result = await build({
  entryPoints: [resolve(root, "receiver/receiver.js")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: ["safari15", "chrome100", "firefox100"],
  minify: true,
  legalComments: "none",
});
const source = result.outputFiles[0]?.text;
if (!source) {
  throw new Error("receiver bundle was not generated");
}
const output = resolve(root, "src/receiver-bundle.generated.ts");
await mkdir(dirname(output), { recursive: true });
await writeFile(
  output,
  `// Generated by npm run build:receiver. Do not edit directly.\nexport const RECEIVER_SCRIPT = ${JSON.stringify(source)};\n`,
  "utf8",
);
